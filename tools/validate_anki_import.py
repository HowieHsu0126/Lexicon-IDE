#!/usr/bin/env python3
"""Validate synthetic APKG fixtures with the official Anki backend in a temporary collection.

Run with an isolated environment containing anki==26.9.3. This never opens a user's Anki profile.
The two fixtures are generated by AnkiCompatibilityFixtureTest on Android, not by this script.
"""
import argparse
import datetime
import importlib.metadata
import json
import tempfile
from pathlib import Path

from anki.collection import Collection
from anki.import_export_pb2 import ImportAnkiPackageRequest, ImportAnkiPackageOptions
from google.protobuf.json_format import MessageToDict


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--updated", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    result = {
        "kind": "official-anki-backend-compatibility",
        "anki_version": importlib.metadata.version("anki"),
        "tested_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "fixtures": "500 synthetic vocabulary cards; no user collection or dictionary data",
        "checks": {},
    }
    options = ImportAnkiPackageOptions(
        merge_notetypes=False, update_notes=0, update_notetypes=0,
        with_scheduling=False, with_deck_configs=False,
    )
    try:
        with tempfile.TemporaryDirectory(prefix="lexicon-anki-validation-") as directory:
            col = Collection(str(Path(directory) / "collection.anki2"))
            try:
                def load(package):
                    log = col.import_anki_package(ImportAnkiPackageRequest(
                        package_path=str(package.resolve()), options=options,
                    ))
                    return MessageToDict(log, preserving_proto_field_name=True)

                def counts():
                    return {"notes": col.db.scalar("SELECT count(*) FROM notes"),
                            "cards": col.db.scalar("SELECT count(*) FROM cards")}

                result["first_import"] = load(args.baseline)
                result["first_counts"] = counts()
                assert counts() == {"notes": 500, "cards": 500}
                row = col.db.first("SELECT id,flds,tags FROM notes WHERE guid=?", "compat-1")
                assert row is not None
                assert len(row[1].split("\x1f")) == 4
                assert "exam::medium" in row[2] and "topic::Education" in row[2]
                result["checks"]["initial_500_notes_500_cards_fields_tags"] = True

                result["repeat_import"] = load(args.baseline)
                result["repeat_counts"] = counts()
                assert counts() == {"notes": 500, "cards": 500}
                result["checks"]["repeat_import_without_duplicates"] = True

                result["updated_import"] = load(args.updated)
                assert counts() == {"notes": 500, "cards": 500}
                fields = col.db.scalar("SELECT flds FROM notes WHERE guid=?", "compat-1")
                assert "Synthetic UPDATED definition" in fields
                result["checks"]["newer_export_updates_existing_note"] = True

                note_id = col.db.scalar("SELECT id FROM notes WHERE guid=?", "compat-1")
                note = col.get_note(note_id)
                note["Back"] = "ANKI-SIDE NEWER EDIT -- SYNTHETIC TEST"
                col.update_note(note)
                result["after_anki_edit_reimport"] = load(args.updated)
                assert col.get_note(note_id)["Back"] == "ANKI-SIDE NEWER EDIT -- SYNTHETIC TEST"
                result["checks"]["if_newer_preserves_newer_anki_edit"] = True
                assert col.db.scalar("SELECT count(*) FROM cards WHERE type<>0 OR reps<>0") == 0
                result["checks"]["no_lexicon_scheduling_imported"] = True
                result["status"] = "passed"
            finally:
                col.close()
    except Exception as exc:
        result["status"] = "failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        raise
    finally:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        print(json.dumps({"status": result.get("status"), "checks": result["checks"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
